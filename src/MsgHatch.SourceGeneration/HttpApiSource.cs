                : source.Append("        return await SendAsync(__request, ").Append(ct).AppendLine(");"))
            .AppendLine("    }")
            .ToString();
    }

    private static void AppendQuery(StringBuilder source, HttpCall call)
    {
        List<IParameterSymbol> queryValues =
            [.. call.Method.Parameters.Where(parameter => !HttpCall.IsBody(parameter) && !call.IsCancellation(parameter) && !call.IsRouteValue(parameter))];
        if (queryValues.Count == 0)
        {
            return;
        }

        source.AppendLine("        var __separator = '?';");
        for (var index = 0; index < queryValues.Count; index++)
        {
            var parameter = queryValues[index];
            if (HttpValues.ItemTypeOf(parameter.Type) is { } itemType)
            {
                var item = "__item" + index;
                source
                    .Append("        if (@").Append(parameter.Name).Append(" is { } __list").Append(index).Append(") { foreach (var ").Append(item)
                    .Append(" in __list").Append(index).Append(") { ").Append(QueryAppendOf(parameter.Name, HttpValues.TextOf(itemType, item))).AppendLine(" } }");
            }
            else if (HttpValues.CanBeNull(parameter.Type))
            {
                var value = "__value" + index;
                source
                    .Append("        if (@").Append(parameter.Name).Append(" is { } ").Append(value).Append(") { ")
                    .Append(QueryAppendOf(parameter.Name, HttpValues.TextOf(HttpValues.ValueTypeOf(parameter.Type), value))).AppendLine(" }");
            }
            else
            {
                source.Append("        ").AppendLine(QueryAppendOf(parameter.Name, HttpValues.TextOf(parameter.Type, "@" + parameter.Name)));
            }
        }
    }

    private static string QueryAppendOf(string name, string text) =>
        $"__uri.Append(__separator).Append({Literal(name + "=")}).Append({text}); __separator = '&';";

    private static string PropertyNameOf(string httpMethod) => httpMethod switch
    {
        "GET" => "Get",
        "POST" => "Post",
        "PUT" => "Put",
        "DELETE" => "Delete",
        _ => "Patch",
    };

    private static string RouteValueOf(IMethodSymbol method, string name)
    {
        var parameter = method.Parameters.First(parameter => parameter.Name == name);
        return HttpValues.TextOf(parameter.Type, "@" + parameter.Name);
    }

    private static string PropertyOf(INamedTypeSymbol json, ITypeSymbol type) =>
        json.GetMembers().OfType<IPropertySymbol>().First(property =>
            property.Type is INamedTypeSymbol { Arity: 1 } info && SymbolEqualityComparer.Default.Equals(info.TypeArguments[0], type)).Name;

