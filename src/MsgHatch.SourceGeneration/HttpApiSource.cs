            .AppendLine(")")
            .AppendLine("    {")
            .AppendLine("        var __uri = new global::System.Text.StringBuilder(_prefix);");
        foreach (var part in call.Route)
        {
            source.Append("        __uri.Append(").Append(part.IsValue ? RouteValueOf(method, part.Text) : Literal(part.Text)).AppendLine(");");
        }

        AppendQuery(source, call);
        source
            .Append("        using var __request = new ").Append(_http).Append(".HttpRequestMessage(").Append(_http).Append(".HttpMethod.")
            .Append(PropertyNameOf(call.HttpMethod)).AppendLine(", UriOf(__uri));");
        if (method.Parameters.FirstOrDefault(HttpCall.IsBody) is { } body)
        {
            source
                .Append("        __request.Content = ").Append(_http).Append(".Json.JsonContent.Create(@").Append(body.Name).Append(", ")
                .Append(context).Append(PropertyOf(json, body.Type)).AppendLine(");");
        }

