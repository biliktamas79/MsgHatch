using System.Text;
using Microsoft.CodeAnalysis;

namespace MsgHatch.SourceGeneration;

/// <summary>The C# source of the placeholder writer of one payload type (section 4.10).</summary>
internal static class WriterSource
{
    private const string _placeholders = "global::MsgHatch.Email.Placeholders";
    private const string _writerClass = "MsgHatchPlaceholderWriter";
    private const string _output = "global::System.Buffers.IBufferWriter<char>";

    public static string For(INamedTypeSymbol type, Compilation compilation)
    {
        var spanFormattable = compilation.GetTypeByMetadataName("System.ISpanFormattable");
        var properties = PropertiesOf(type);
        var self = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine();
        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            source.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";").AppendLine();
        }

        var containers = ContainersOf(type);
        foreach (var container in containers)
        {
            source.Append("partial ").Append(KeywordOf(container)).Append(' ').AppendLine(NameOf(container)).AppendLine("{");
        }

        source
            .Append("partial ").Append(KeywordOf(type)).Append(' ').Append(NameOf(type))
            .Append(" : ").Append(_placeholders).Append(".IPlaceholderPayload<").Append(self).AppendLine(">")
            .AppendLine("{")
            .Append("    static ").Append(_placeholders).Append(".IPlaceholderWriter<").Append(self).Append("> ")
            .Append(_placeholders).Append(".IPlaceholderPayload<").Append(self).Append(">.Writer => ")
            .Append(_writerClass).AppendLine(".Instance;")
            .AppendLine()
            .Append("    private sealed class ").Append(_writerClass).Append(" : ")
            .Append(_placeholders).Append(".IPlaceholderWriter<").Append(self).AppendLine(">")
            .AppendLine("    {")
            .Append("        public static readonly ").Append(_writerClass).Append(" Instance = new ").Append(_writerClass).AppendLine("();")
            .AppendLine()
            .AppendLine("        public int IndexOf(global::System.ReadOnlySpan<char> propertyName) => propertyName switch")
            .AppendLine("        {");
        for (var index = 0; index < properties.Count; index++)
        {
            source.Append("            \"").Append(properties[index].Name).Append("\" => ").Append(index).AppendLine(",");
        }

        source
            .AppendLine("            _ => -1,")
            .AppendLine("        };")
            .AppendLine()
            .Append("        public bool TryWrite(in ").Append(self).Append(" payload, int propertyIndex, ").Append(_output)
            .AppendLine(" output, global::System.IFormatProvider culture)")
            .AppendLine("        {")
            .AppendLine("            switch (propertyIndex)")
            .AppendLine("            {");
        for (var index = 0; index < properties.Count; index++)
        {
            source
                .Append("                case ").Append(index).Append(": { ")
                .Append(WriteStatementOf(properties[index], spanFormattable))
                .AppendLine(" return true; }");
        }

        source
            .AppendLine("                default: return false;")
            .AppendLine("            }")
            .AppendLine("        }")
            .AppendLine()
            .Append("        private static void WriteText(string? value, ").Append(_output).AppendLine(" output)")
            .AppendLine("        {")
            .AppendLine("            if (value is null) return;")
            .AppendLine("            global::System.MemoryExtensions.AsSpan(value).CopyTo(output.GetSpan(value.Length));")
            .AppendLine("            output.Advance(value.Length);")
            .AppendLine("        }")
            .AppendLine()
            .Append("        private static void WriteFormattable<T>(T value, ").Append(_output)
            .AppendLine(" output, global::System.IFormatProvider culture)")
            .AppendLine("            where T : global::System.ISpanFormattable")
            .AppendLine("        {")
            .AppendLine("            var size = 32;")
            .AppendLine("            while (true)")
            .AppendLine("            {")
            .AppendLine("                var span = output.GetSpan(size);")
            .AppendLine("                if (value.TryFormat(span, out var written, default, culture))")
            .AppendLine("                {")
            .AppendLine("                    output.Advance(written);")
            .AppendLine("                    return;")
            .AppendLine("                }")
            .AppendLine()
            .AppendLine("                size = span.Length * 2;")
            .AppendLine("            }")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine("}");
        foreach (var _ in containers)
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static List<IPropertySymbol> PropertiesOf(INamedTypeSymbol type)
    {
        var properties = new List<IPropertySymbol>();
        var names = new HashSet<string>(StringComparer.Ordinal);
        for (var current = type; current is { SpecialType: not SpecialType.System_Object }; current = current.BaseType)
        {
            properties.AddRange(current.GetMembers().OfType<IPropertySymbol>().Where(property => IsPlaceholder(property) && names.Add(property.Name)));
        }

        return properties;
    }

    private static bool IsPlaceholder(IPropertySymbol property) =>
        property is { DeclaredAccessibility: Accessibility.Public, IsStatic: false, IsIndexer: false, GetMethod.DeclaredAccessibility: Accessibility.Public };

    private static string WriteStatementOf(IPropertySymbol property, INamedTypeSymbol? spanFormattable)
    {
        var value = "payload.@" + property.Name;
        var type = property.Type;
        if (type.SpecialType == SpecialType.System_String)
        {
            return $"WriteText({value}, output);";
        }

        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
            && Implements(nullable.TypeArguments[0], spanFormattable))
        {
            return $"if ({value} is {{ }} value) WriteFormattable(value, output, culture);";
        }

        if (Implements(type, spanFormattable))
        {
            return type.IsValueType
                ? $"WriteFormattable({value}, output, culture);"
                : $"if ({value} is {{ }} value) WriteFormattable(value, output, culture);";
        }

        // ponytail: ToString allocates, add a writer interface for custom types if a benchmark shows the need
        return type.IsValueType && type.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T
            ? $"WriteText({value}.ToString(), output);"
            : $"WriteText({value}?.ToString(), output);";
    }

    private static bool Implements(ITypeSymbol type, INamedTypeSymbol? spanFormattable) =>
        spanFormattable is not null && type.AllInterfaces.Contains(spanFormattable, SymbolEqualityComparer.Default);

    private static List<INamedTypeSymbol> ContainersOf(INamedTypeSymbol type)
    {
        var containers = new List<INamedTypeSymbol>();
        for (var container = type.ContainingType; container is not null; container = container.ContainingType)
        {
            containers.Insert(0, container);
        }

        return containers;
    }

    private static string NameOf(INamedTypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);

    private static string KeywordOf(INamedTypeSymbol type) => (type.IsRecord, type.TypeKind) switch
    {
        (true, TypeKind.Struct) => "record struct",
        (true, _) => "record",
        (_, TypeKind.Struct) => "struct",
        (_, TypeKind.Interface) => "interface",
        _ => "class",
    };
}
